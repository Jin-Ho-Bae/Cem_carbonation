# ──────────── LAMMPS Script Generators ────────────

def generate_elastic_constants_script(structure_file, potential_file,
                                       potential_type="reaxff",
                                       temperature=300.0):
    script = f"""# Elastic Constants Calculation
# Auto-generated by Carbon Mineralization Agent

units           real
atom_style      charge
boundary        p p p

read_data       {structure_file}

pair_style      {potential_type}
pair_coeff      * * {potential_file}

# Minimize
minimize        1.0e-6 1.0e-8 1000 10000
reset_timestep  0

# NPT equilibration
fix             1 all npt temp {temperature} {temperature} 100 iso 0 0 1000
timestep        0.5
thermo          100
run             10000
unfix           1

# Store equilibrium box
variable        lx0 equal lx
variable        ly0 equal ly
variable        lz0 equal lz
variable        vol0 equal vol

# 6 deformations for full elastic tensor
variable        delta equal 0.01  # 1% strain

# xx deformation
change_box      all x delta 0 ${{delta}} units box remap
fix             2 all nve
run             1000
variable        sxx equal pxx
variable        syy equal pyy
variable        szz equal pzz
variable        sxy equal pxy
variable        sxz equal pxz
variable        syz equal pyz

print           "C11 = ${{sxx}}  C12 = ${{syy}}  C13 = ${{szz}}"

# Reset and repeat for yy, zz, yz, xz, xy...
print           "Elastic constants calculation complete"
"""
    return script


def generate_diffusion_script(structure_file, potential_file,
                               diffusant="CO2", temperature=300.0,
                               run_time_ps=1000.0):
    script = f"""# Diffusion Coefficient via MSD
# Diffusant: {diffusant}, T = {temperature} K

units           real
atom_style      full
boundary        p p p

read_data       {structure_file}

pair_style      lj/cut/coul/long 12.0
pair_coeff      * * {potential_file}
kspace_style    pppm 1.0e-4

# Equilibrate
fix             1 all nvt temp {temperature} {temperature} 100
timestep        1.0
run             50000
unfix           1

# Production with MSD tracking
compute         msd_diff diffusant_group msd com yes
fix             msd_out all ave/time 100 1 100 c_msd_diff[4] file msd_{diffusant}.dat

fix             2 all nvt temp {temperature} {temperature} 100
run             {int(run_time_ps * 1000)}

# D = MSD / (6 * t) for 3D
print           "MSD data written to msd_{diffusant}.dat"
print           "Post-process: D = slope(MSD vs t) / 6"
"""
    return script


# ──────────── MD Computation Interface ────────────

class MDEngine:
    def __init__(self, lammps_path=None):
        self.lammps_path = lammps_path or self._find_lammps()
        self.has_lammps = self.lammps_path is not None

    def _find_lammps(self):
        for path in ["lmp", "lmp_serial", "lmp_mpi", "lammps"]:
            try:
                subprocess.run([path, "-h"], capture_output=True, timeout=5)
                return path
            except (FileNotFoundError, subprocess.TimeoutExpired):
                continue
        return None

    def get_elastic_properties(self, phase, temperature=300.0):
        if phase in MD_REFERENCE_DATA:
            data = MD_REFERENCE_DATA[phase]
            if "E" in data:
                return MDResult(
                    property_name="elastic_modulus",
                    value=data["E"]["value"],
                    unit=data["E"]["unit"],
                    temperature=temperature,
                    method=f"MD-{data['E'].get('method', 'reference')}",
                    confidence=data["E"].get("confidence", "medium"),
                    details=data,
                )
        return MDResult(
            property_name="elastic_modulus", value=0.0, unit="Pa",
            temperature=temperature, method="not_available",
            confidence="low", details={"error": f"No data for phase '{phase}'"},
        )

    def get_diffusion_coefficient(self, species, medium="pore", temperature=300.0):
        key = f"{species}_in_{medium}" if medium != "pore" else f"{species}_in_pore"
        lookup_keys = [key, species, medium]
        for k in lookup_keys:
            if k in MD_REFERENCE_DATA:
                data = MD_REFERENCE_DATA[k]
                for prop_key in [f"D_{species}", f"D_{species}_gas", f"D_{species}_water"]:
                    if prop_key in data:
                        return MDResult(
                            property_name=f"D_{species}",
                            value=data[prop_key]["value"],
                            unit=data[prop_key]["unit"],
                            temperature=temperature,
                            method=f"MD-{data[prop_key].get('method', 'reference')}",
                            confidence=data[prop_key].get("confidence", "medium"),
                            details=data,
                        )
        return MDResult(
            property_name=f"D_{species}", value=0.0, unit="m^2/s",
            temperature=temperature, method="not_available",
            confidence="low", details={"error": f"No diffusion data for {species} in {medium}"},
        )

    def run_lammps_script(self, script, work_dir=None):
        if not self.has_lammps:
            return {"status": "error", "message": "LAMMPS not installed",
                    "suggestion": "Install LAMMPS: pip install lammps or apt-get install lammps"}
        work_dir = work_dir or tempfile.mkdtemp(prefix="lammps_")
        script_path = os.path.join(work_dir, "in.lammps")
        with open(script_path, "w") as f:
            f.write(script)
        try:
            result = subprocess.run(
                [self.lammps_path, "-in", script_path],
                capture_output=True, text=True, timeout=3600, cwd=work_dir,
            )
            return {
                "status": "success" if result.returncode == 0 else "error",
                "stdout": result.stdout, "stderr": result.stderr,
                "work_dir": work_dir,
            }
        except subprocess.TimeoutExpired:
            return {"status": "timeout", "work_dir": work_dir}

    def install_lammps_colab(self):
        try:
            subprocess.run(["pip", "install", "lammps"], check=True, capture_output=True)
            self.has_lammps = True
            self.lammps_path = "lmp"
            return True
        except subprocess.CalledProcessError:
            try:
                subprocess.run(["apt-get", "install", "-y", "lammps"],
                               check=True, capture_output=True)
                self.has_lammps = True
                self.lammps_path = "lmp"
                return True
            except subprocess.CalledProcessError:
                return False
